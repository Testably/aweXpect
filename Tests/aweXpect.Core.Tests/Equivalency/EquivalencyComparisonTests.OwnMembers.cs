	/// <summary>
	///     Has enough items to be remembered once it was found equivalent.
	/// </summary>
	private sealed class HeavyList : List<WithProperty>
	{
		private readonly ReadCounter _counter;
		private readonly string _name;

		public HeavyList(ReadCounter counter, string name)
		{
			_counter = counter;
			_name = name;
			AddRange(Enumerable.Range(0, 100).Select(i => new WithProperty(i)));
		}

		public string Name
		{
			get
			{
				_counter.Reads++;
				return _name;
			}
		}
	}

	private sealed class ReadCounter
	{
		public int Reads { get; set; }
	}

	/// <summary>
	///     Implements the sequence itself, and its <see cref="Count" /> for the interface of the framework, which
	///     says nothing about the number of its items.
	/// </summary>
	private sealed class SelfMadePage<T>(string name, int count, params T[] items) : IReadOnlyCollection<T>
	{
		public string Name { get; } = name;

		public int Count { get; } = count;

		public IEnumerator<T> GetEnumerator() => ((IEnumerable<T>)items).GetEnumerator();

		IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();
	}

	private sealed class SelfMadeLookup(string name, int count, Dictionary<string, int> entries)
		: IReadOnlyDictionary<string, int>
	{
		public string Name { get; } = name;

		public int this[string key] => entries[key];

		public IEnumerable<string> Keys => entries.Keys.Concat([Name,]);

		public IEnumerable<int> Values => entries.Values.Concat([Count,]);

		public int Count { get; } = count;

		public bool ContainsKey(string key) => entries.ContainsKey(key);

		public bool TryGetValue(string key, out int value) => entries.TryGetValue(key, out value);

		public IEnumerator<KeyValuePair<string, int>> GetEnumerator() => entries.GetEnumerator();

		IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();
	}

	private readonly struct LabeledPair(string label, params int[] items) : IEnumerable<int>
	{
		public readonly string Label = label;

		public IEnumerator<int> GetEnumerator() => ((IEnumerable<int>)items).GetEnumerator();

		IEnumerator IEnumerable.GetEnumerator() => GetEnumerator();
	}
