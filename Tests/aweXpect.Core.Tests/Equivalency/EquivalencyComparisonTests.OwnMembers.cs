	private static NamedList CreateNamedList(string name, params int[] items)
	{
		NamedList list = new()
		{
			Name = name,
		};
		list.AddRange(items);
		return list;
	}

	private static IEnumerable<int> Iterate(int value, int unused)
	{
		yield return value;
		if (unused < 0)
		{
			yield return unused;
		}
	}

	/// <remarks>
	///     The registered accessor differs from the property, so that a comparison shows which of them it used.
	/// </remarks>
	private static void RegisterShoutingList()
		=> TypeMetadataRegistry.RegisterBatch(() =>
		{
			TypeMetadataRegistry.RegisterProperty<RegisteredList, string>(nameof(RegisteredList.Name),
				o => o.Name.ToUpperInvariant() + "!");
			TypeMetadataRegistry.RegisterCollection<RegisteredList>();
		});

	private class NamedList : List<int>
