using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace aweXpect.Core.Generators;

/// <summary>
///     Writes the source of an <see cref="ExpectationModel" />.
/// </summary>
/// <remarks>
///     Every type is fully qualified, so that the generated code binds the same in any namespace and without the usings
///     of the declaring file.
/// </remarks>
internal static class ExpectationWriter
{
	private const string ConstraintResult = "global::aweXpect.Core.Constraints.ConstraintResult";
	internal const string Formatter = "global::aweXpect.Formatting.Format.Formatter";
	internal const string Grammars = "global::aweXpect.Core.ExpectationGrammars";
	internal const string GrammarsExtensions = "global::aweXpect.Core.ExpectationGrammarsExtensions";
	private const string Outcome = "global::aweXpect.Core.Constraints.Outcome";
	internal const string PredicateResult = "global::aweXpect.Core.Extending.PredicateResult";
	internal const string StringBuilder = "global::System.Text.StringBuilder";
	internal const string ValueFormatters = "global::aweXpect.Formatting.ValueFormatters";
	internal const string ValueTask = "global::System.Threading.Tasks.ValueTask";

	public static string Write(ExpectationModel model)
	{
		StringBuilder sb = new();
		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine("#nullable enable");
		sb.AppendLine();
		AppendUsings(sb, model.Usings);
		if (model.Namespace is not null)
		{
			sb.Append("namespace ").AppendLine(model.Namespace);
			sb.AppendLine("{");
			AppendUsings(sb, model.NamespaceUsings);
		}

		sb.Append(model.ClassAccessibility).Append(" static partial class ").AppendLine(model.ClassName);
		sb.AppendLine("{");
		foreach (OverloadModel overload in model.Overloads.Values)
		{
			AppendExpectation(sb, model, overload, false);
			if (model.NegatedName is not null)
			{
				AppendExpectation(sb, model, overload, true);
			}
		}

		foreach (OverloadModel overload in model.Overloads.Values)
		{
			AppendConstraint(sb, model, overload);
		}

		sb.AppendLine("}");
		if (model.Namespace is not null)
		{
			sb.AppendLine("}");
		}

		return sb.ToString();
	}

	internal static void AppendUsings(StringBuilder sb, EquatableArray<string> usings)
	{
		foreach (string directive in usings.Values)
		{
			sb.AppendLine(directive);
		}

		if (usings.Count > 0)
		{
			sb.AppendLine();
		}
	}

	private static void AppendExpectation(StringBuilder sb, ExpectationModel model, OverloadModel overload,
		bool negated)
	{
		string valueType = negated ? overload.NegatedResultType : overload.PositiveResultType;
		string resultType =
			$"global::aweXpect.Results.AndOrResult<{valueType}, global::aweXpect.Core.IThat<{overload.ThatType}>>";
		AppendExpectationHeader(sb, model, overload, negated);
		sb.Append('\t').Append(model.MethodAccessibility).Append(" static ").Append(resultType).Append(' ')
			.Append(negated ? model.NegatedName : model.PositiveName)
			.Append("(this global::aweXpect.Core.IThat<").Append(overload.ThatType).Append("> subject");
		foreach (ParameterModel parameter in model.Parameters.Values)
		{
			sb.Append(", ").Append(parameter.IsParams ? "params " : "").Append(parameter.Type).Append(' ')
				.Append(parameter.GetName(negated));
		}

		sb.AppendLine(")");
		sb.AppendLine("\t{");
		AppendNullChecks(sb, model.Parameters, negated);
		string arguments = string.Concat(Enumerable.Range(0, model.Parameters.Count)
			.Select(i => model.Parameters.Count == 1 ? ", __state" : $", __state.Item{i + 1}"));
		string constraint = $"new {overload.ConstraintName}(__it, __grammars{arguments})";
		if (negated)
		{
			constraint = $"global::aweXpect.Core.Constraints.ConstraintResultExtensions.Invert({constraint})";
		}

		sb.Append("\t\treturn new ").Append(resultType)
			.Append("(global::aweXpect.Core.Extending.ThatExtensions.Get(subject).ExpectationBuilder.AddConstraint(");
		AppendConstraintArguments(sb, model, constraint, negated);
		sb.AppendLine("),");
		sb.AppendLine("\t\t\tsubject);");
		sb.AppendLine("\t}");
		sb.AppendLine();
	}

	private static void AppendExpectationHeader(StringBuilder sb, ExpectationModel model, OverloadModel overload,
		bool negated)
	{
		sb.AppendLine("\t/// <summary>");
		AppendDocumentation(sb, (negated ? model.NegatedSummary : model.Summary) ??
		                        $"Verifies that the subject {ToDocumentation(negated ? model.NegatedText : model.PositiveText, model, negated)}.");
		sb.AppendLine("\t/// </summary>");
		if ((negated ? model.NegatedRemarks : model.Remarks) is { Length: > 0, } remarks)
		{
			sb.AppendLine("\t/// <remarks>");
			AppendDocumentation(sb, remarks);
			sb.AppendLine("\t/// </remarks>");
		}

		if (negated ? overload.NegatedGuaranteesNotNull : overload.PositiveGuaranteesNotNull)
		{
			sb.AppendLine("\t[global::aweXpect.Core.GuaranteesNotNull]");
		}
	}

	internal static void AppendNullChecks(StringBuilder sb, EquatableArray<ParameterModel> parameters, bool negated)
	{
		foreach (string name in parameters.Values.Where(p => p.RequiresNotNull).Select(p => p.GetName(negated)))
		{
			string rawName = name.TrimStart('@');
			// Like the null message of aweXpect.Core, the polarity names, which are adjectives, are followed by a noun.
			string description = rawName is "expected" or "unexpected" ? $"'{rawName}' value" : $"'{rawName}'";
			sb.Append("\t\tif (").Append(name).AppendLine(" is null)");
			sb.AppendLine("\t\t{");
			sb.Append("\t\t\tthrow global::aweXpect.Core.Tracing.WriteException(new global::System.ArgumentNullException(nameof(")
				.Append(name).Append("), \"The ").Append(description).AppendLine(" cannot be null.\"));");
			sb.AppendLine("\t\t}");
			sb.AppendLine();
		}
	}

	private static void AppendConstraintArguments(StringBuilder sb, ExpectationModel model, string constraint,
		bool negated)
	{
		switch (model.Parameters.Count)
		{
			case 0:
				sb.Append("(__it, __grammars) => ").Append(constraint);
				break;
			case 1:
				sb.Append(model.Parameters.Values[0].GetName(negated)).Append(", (__state, __it, __grammars) => ")
					.Append(constraint);
				break;
			default:
				sb.Append('(').Append(string.Join(", ", model.Parameters.Values.Select(p => p.GetName(negated))))
					.Append("), (__state, __it, __grammars) => ").Append(constraint);
				break;
		}
	}

	private static void AppendConstraint(StringBuilder sb, ExpectationModel model, OverloadModel overload)
	{
		string owner = model.Namespace is null
			? $"global::{model.ClassName}"
			: $"global::{model.Namespace}.{model.ClassName}";
		string fields = string.Concat(Enumerable.Range(0, model.Parameters.Count).Select(i => $", _p{i}"));

		AppendConstraintDeclaration(sb, model, overload);
		AppendIsMetBy(sb, model, overload, owner);
		AppendTextMethod(sb, "AppendNormalExpectation", model.PositiveText);
		AppendTextMethod(sb, "AppendNegatedExpectation", model.NegatedText);
		AppendResultMethods(sb, model, overload, owner, fields);
		sb.AppendLine("\t}");
	}

	private static void AppendConstraintDeclaration(StringBuilder sb, ExpectationModel model, OverloadModel overload)
	{
		string helper = overload.FailsOnNull ? "WithNotNullValue" : "WithValue";
		string constraintInterface = model.IsAsync || model.PassesCancellationToken
			? "IAsyncConstraint"
			: "IValueConstraint";

		sb.Append("\tprivate sealed class ").Append(overload.ConstraintName).Append(" : ")
			.Append(ConstraintResult).Append('.').Append(helper).Append('<').Append(overload.ThatType).AppendLine(">,");
		sb.Append("\t\tglobal::aweXpect.Core.Constraints.").Append(constraintInterface).Append('<')
			.Append(overload.ThatType).AppendLine(">");
		sb.AppendLine("\t{");
		for (int i = 0; i < model.Parameters.Count; i++)
		{
			sb.Append("\t\tprivate readonly ").Append(model.Parameters.Values[i].Type).Append(" _p").Append(i)
				.AppendLine(";");
		}

		if (model.ReturnsPredicateResult)
		{
			sb.AppendLine("\t\tprivate string? _reason;");
		}

		if (model.Parameters.Count > 0 || model.ReturnsPredicateResult)
		{
			sb.AppendLine();
		}

		sb.Append("\t\tpublic ").Append(overload.ConstraintName).Append("(string it, ").Append(Grammars)
			.Append(" grammars");
		for (int i = 0; i < model.Parameters.Count; i++)
		{
			sb.Append(", ").Append(model.Parameters.Values[i].Type).Append(" p").Append(i);
		}

		sb.AppendLine(")");
		sb.AppendLine("\t\t\t: base(it, grammars)");
		sb.AppendLine("\t\t{");
		for (int i = 0; i < model.Parameters.Count; i++)
		{
			sb.Append("\t\t\t_p").Append(i).Append(" = p").Append(i).AppendLine(";");
		}

		sb.AppendLine("\t\t}");
		sb.AppendLine();
	}

	private static void AppendIsMetBy(StringBuilder sb, ExpectationModel model, OverloadModel overload, string owner)
	{
		string call = $"{owner}.{model.PredicateName}({overload.SubjectArgument}"
		              + $"{GetArguments(model.Parameters.Count, model.CancellationTokenIndex)})";
		string returnValue = "this";
		if (model.IsAsync)
		{
			call = $"await {call}";
			sb.Append("\t\tpublic async ").Append(ValueTask).Append('<').Append(ConstraintResult)
				.Append("> IsMetBy(").Append(overload.ThatType)
				.AppendLine(" actual, global::System.Threading.CancellationToken cancellationToken)");
		}
		else if (model.PassesCancellationToken)
		{
			// Only the asynchronous constraint receives the token, so a synchronous predicate completes it at once.
			returnValue = $"new {ValueTask}<{ConstraintResult}>(this)";
			sb.Append("\t\tpublic ").Append(ValueTask).Append('<').Append(ConstraintResult)
				.Append("> IsMetBy(").Append(overload.ThatType)
				.AppendLine(" actual, global::System.Threading.CancellationToken cancellationToken)");
		}
		else
		{
			sb.Append("\t\tpublic ").Append(ConstraintResult).Append(" IsMetBy(").Append(overload.ThatType)
				.AppendLine(" actual)");
		}

		sb.AppendLine("\t\t{");
		sb.AppendLine("\t\t\tActual = actual;");
		if (model.ReturnsPredicateResult)
		{
			AppendPredicateResult(sb, overload, call, returnValue);
		}
		else
		{
			sb.Append("\t\t\tOutcome = ").Append(overload.FailsOnNull ? "!(actual is null) && " : "").Append(call)
				.Append(" ? ").Append(Outcome).Append(".Success : ").Append(Outcome).AppendLine(".Failure;");
		}

		sb.Append("\t\t\treturn ").Append(returnValue).AppendLine(";");
		sb.AppendLine("\t\t}");
		sb.AppendLine();
	}

	private static void AppendPredicateResult(StringBuilder sb, OverloadModel overload, string call,
		string returnValue)
	{
		sb.AppendLine("\t\t\t_reason = null;");
		if (overload.FailsOnNull)
		{
			sb.AppendLine("\t\t\tif (actual is null)");
			sb.AppendLine("\t\t\t{");
			sb.Append("\t\t\t\tOutcome = ").Append(Outcome).AppendLine(".Failure;");
			sb.Append("\t\t\t\treturn ").Append(returnValue).AppendLine(";");
			sb.AppendLine("\t\t\t}");
			sb.AppendLine();
		}

		sb.Append("\t\t\t").Append(PredicateResult).Append(" result = ").Append(call).AppendLine(";");
		sb.AppendLine("\t\t\t_reason = result.Reason;");
		sb.AppendLine("\t\t\tOutcome = result.Outcome;");
	}

	private static void AppendResultMethods(StringBuilder sb, ExpectationModel model, OverloadModel overload,
		string owner, string fields)
	{
		sb.Append("\t\tprotected override void AppendNormalResult(").Append(StringBuilder)
			.AppendLine(" stringBuilder, string? indentation = null)");
		sb.AppendLine("\t\t{");
		if (model.ReturnsPredicateResult)
		{
			sb.AppendLine("\t\t\tif (!(_reason is null))");
			sb.AppendLine("\t\t\t{");
			sb.AppendLine("\t\t\t\tstringBuilder.Append(It).Append(' ').Append(_reason);");
			sb.AppendLine("\t\t\t\treturn;");
			sb.AppendLine("\t\t\t}");
			sb.AppendLine();
		}

		if (model.Result is not { } result)
		{
			sb.Append("\t\t\tstringBuilder.Append(It).Append(").Append(GrammarsExtensions)
				.AppendLine(".SubjectVerb(Grammars, It, \" was \", \" were \"));");
			sb.Append("\t\t\t").Append(ValueFormatters).Append(".Format(").Append(Formatter)
				.AppendLine(", stringBuilder, Actual);");
		}
		else
		{
			sb.Append(result.TakesItAndGrammars
					? "\t\t\tstringBuilder.Append("
					: "\t\t\tstringBuilder.Append(It).Append(' ').Append(")
				.Append(owner).Append('.').Append(result.Name).Append('(').Append(overload.ResultArgument)
				.Append(result.TakesParameters ? fields : "")
				.Append(result.TakesItAndGrammars ? ", It, Grammars" : "").AppendLine("));");
		}

		sb.AppendLine("\t\t}");
		sb.AppendLine();
		sb.Append("\t\tprotected override void AppendNegatedResult(").Append(StringBuilder)
			.AppendLine(" stringBuilder, string? indentation = null)");
		sb.AppendLine("\t\t\t=> AppendNormalResult(stringBuilder, indentation);");
	}

	private static void AppendTextMethod(StringBuilder sb, string name, EquatableArray<TextPart> parts)
	{
		sb.Append("\t\tprotected override void ").Append(name).Append('(').Append(StringBuilder)
			.AppendLine(" stringBuilder, string? indentation = null)");
		sb.AppendLine("\t\t{");
		for (int i = 0; i < parts.Count; i++)
		{
			TextPart part = parts.Values[i];
			if (part.Text is null)
			{
				sb.Append("\t\t\t").Append(ValueFormatters).Append(".Format(").Append(Formatter)
					.Append(", stringBuilder, _p").Append(part.ParameterIndex).AppendLine(");");
				continue;
			}

			string? plural = i == 0 ? GetPlural(part.Text) : null;
			sb.Append("\t\t\tstringBuilder.Append(");
			if (plural is null)
			{
				sb.Append(Literal(part.Text));
			}
			else
			{
				sb.Append(GrammarsExtensions).Append(".Verb(Grammars, ").Append(Literal(part.Text)).Append(", ")
					.Append(Literal(plural)).Append(')');
			}

			sb.AppendLine(");");
		}

		sb.AppendLine("\t\t}");
		sb.AppendLine();
	}

	/// <summary>
	///     The plural form of the <paramref name="text" />, or <see langword="null" /> when its leading verb has none.
	/// </summary>
	private static string? GetPlural(string text)
	{
		int space = text.IndexOf(' ');
		string head = space < 0 ? text : text.Substring(0, space);
		string tail = space < 0 ? "" : text.Substring(space);
		return head switch
		{
			"is" => "are" + tail,
			"has" => "have" + tail,
			"does" => "do" + tail,
			_ => null,
		};
	}

	private static string ToDocumentation(EquatableArray<TextPart> parts, ExpectationModel model, bool negated)
		=> string.Concat(parts.Values.Select(part => part.Text is null
			? $"<paramref name=\"{model.Parameters.Values[part.ParameterIndex].GetName(negated).TrimStart('@')}\" />"
			: EscapeXml(part.Text)));

	internal static void AppendDocumentation(StringBuilder sb, string text)
	{
		foreach (string line in text.Replace("\r\n", "\n").Split('\n'))
		{
			sb.Append("\t///     ").AppendLine(line.Trim());
		}
	}

	/// <summary>
	///     The arguments of the predicate after the subject: the fields of the parameters, with the cancellation token of
	///     the evaluation at its position.
	/// </summary>
	internal static string GetArguments(int parameterCount, int cancellationTokenIndex)
	{
		List<string> arguments = Enumerable.Range(0, parameterCount).Select(i => $"_p{i}").ToList();
		if (cancellationTokenIndex >= 0)
		{
			arguments.Insert(cancellationTokenIndex, "cancellationToken");
		}

		return string.Concat(arguments.Select(argument => ", " + argument));
	}

	internal static string EscapeXml(string text)
		=> text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

	internal static string Literal(string text)
		=> SymbolDisplay.FormatLiteral(text, true);
}
