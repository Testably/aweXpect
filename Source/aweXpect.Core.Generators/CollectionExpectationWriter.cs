using System.Text;
using static aweXpect.Core.Generators.ExpectationWriter;

namespace aweXpect.Core.Generators;

/// <summary>
///     Writes the source of a <see cref="CollectionExpectationModel" />.
/// </summary>
/// <remarks>
///     Every type is fully qualified, so that the generated code binds the same in any namespace and without the usings
///     of the declaring file.
/// </remarks>
internal static class CollectionExpectationWriter
{
	private const string EnumerableType = "global::System.Collections.Generic.IEnumerable";
	private const string AsyncEnumerableType = "global::System.Collections.Generic.IAsyncEnumerable";
	private const string EnumerableQuantifier = "global::aweXpect.Options.EnumerableQuantifier";
	private const string FormattingOptions = "global::aweXpect.Formatting.FormattingOptions";

	public static string Write(CollectionExpectationModel model)
	{
		ClassModel classModel = model.Class;
		StringBuilder sb = new();
		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine("#nullable enable");
		sb.AppendLine();
		AppendUsings(sb, classModel.Usings);
		if (classModel.Namespace is not null)
		{
			sb.Append("namespace ").AppendLine(classModel.Namespace);
			sb.AppendLine("{");
			AppendUsings(sb, classModel.NamespaceUsings);
		}

		sb.Append(classModel.ClassAccessibility).Append(" static partial class ").AppendLine(classModel.ClassName);
		sb.AppendLine("{");
		foreach (ItemModel item in model.Items.Values)
		{
			AppendExpectations(sb, model, item);
		}

		AppendConstraints(sb, model);
		sb.AppendLine("}");
		if (classModel.Namespace is not null)
		{
			sb.AppendLine("}");
		}

		return sb.ToString();
	}

	/// <summary>
	///     Appends the expectations on every kind of collection that holds the <paramref name="item" />.
	/// </summary>
	private static void AppendExpectations(StringBuilder sb, CollectionExpectationModel model, ItemModel item)
	{
		AppendExpectation(sb, model, $"global::aweXpect.IEnumerableItems<{item.ItemType}>",
			$"{EnumerableType}<{item.ItemType}>",
			SyncConstraintOf(model, item, $"{EnumerableType}<{item.ItemType}>?"), null);

		AppendExpectation(sb, model, $"global::aweXpect.IStructEnumerableItems<TCollection, {item.ItemType}>",
			"TCollection", SyncConstraintOf(model, item, "TCollection"), $"{EnumerableType}<{item.ItemType}>");

		if (model.SupportsAsyncEnumerables)
		{
			AppendExpectation(sb, model, $"global::aweXpect.IAsyncEnumerableItems<{item.ItemType}>",
				$"{AsyncEnumerableType}<{item.ItemType}>",
				AsyncConstraintOf(model, item), null);
		}

		if (model.CollectionOverload)
		{
			AppendCollectionExpectations(sb, model, item, model.Name, "all items", false);
		}

		if (model.NegatedName is { } negatedName)
		{
			AppendCollectionExpectations(sb, model, item, negatedName, "no items", true);
		}
	}

	/// <summary>
	///     Appends the expectations directly on the collections of the <paramref name="item" /> that require all items
	///     to match, or with <paramref name="negated" /> no item.
	/// </summary>
	/// <param name="sb">The source to append to.</param>
	/// <param name="model">The expectation.</param>
	/// <param name="item">The item type.</param>
	/// <param name="name">The name of the expectation.</param>
	/// <param name="items">The items that the quantifier selects in the summary, e.g. "all items".</param>
	/// <param name="negated">
	///     Whether the expectation is the negated one, which requires no item to match and whose parameters have their
	///     negated names.
	/// </param>
	private static void AppendCollectionExpectations(StringBuilder sb, CollectionExpectationModel model,
		ItemModel item, string name, string items, bool negated)
	{
		string summary = $"Verifies that {items} {ToDocumentation(model.PluralText, model.Class, negated)}.";
		AppendCollectionExpectation(sb, model, name, $"{EnumerableType}<{item.ItemType}>",
			SyncConstraintOf(model, item, $"{EnumerableType}<{item.ItemType}>?"), summary, negated);
		if (model.SupportsAsyncEnumerables)
		{
			AppendCollectionExpectation(sb, model, name, $"{AsyncEnumerableType}<{item.ItemType}>",
				AsyncConstraintOf(model, item), summary, negated);
		}
	}

	/// <summary>
	///     The synchronous constraint of the <paramref name="item" /> for the <paramref name="collection" />.
	/// </summary>
	private static string SyncConstraintOf(CollectionExpectationModel model, ItemModel item, string collection)
		=> model.ItemTypeParameter is { } itemType
			? $"{SyncConstraint(item)}<{collection}, {itemType}>"
			: $"{SyncConstraint(item)}<{collection}>";

	/// <summary>
	///     The asynchronous constraint of the <paramref name="item" />.
	/// </summary>
	private static string AsyncConstraintOf(CollectionExpectationModel model, ItemModel item)
		=> model.ItemTypeParameter is { } itemType
			? $"{AsyncConstraint(item)}<{itemType}>"
			: AsyncConstraint(item);

	/// <summary>
	///     The type parameters of a generated method or class, with the type parameter of the item at the end.
	/// </summary>
	private static string TypeParameters(CollectionExpectationModel model, string? typeParameter)
	{
		List<string> typeParameters = [];
		if (typeParameter is not null)
		{
			typeParameters.Add(typeParameter);
		}

		if (model.ItemTypeParameter is { } itemType)
		{
			typeParameters.Add(itemType);
		}

		return typeParameters.Count == 0 ? "" : $"<{string.Join(", ", typeParameters)}>";
	}

	/// <summary>
	///     Appends the constraints of the type parameter of the item, if any.
	/// </summary>
	private static void AppendItemTypeConstraints(StringBuilder sb, CollectionExpectationModel model)
	{
		if (model.ItemTypeParameter is { } itemType)
		{
			sb.Append("\t\twhere ").Append(itemType).Append(" : ").AppendLine(model.ItemTypeConstraints);
		}
	}

	/// <param name="sb">The source to append to.</param>
	/// <param name="model">The expectation.</param>
	/// <param name="name">The name of the expectation.</param>
	/// <param name="collection">The type of the extended collection.</param>
	/// <param name="constraint">The constructed constraint.</param>
	/// <param name="summary">The XML documentation of the summary.</param>
	/// <param name="negated">
	///     Whether the expectation is the negated one, which requires no item to match and whose parameters have their
	///     negated names.
	/// </param>
	/// <remarks>
	///     The quantifier of the negated expectation names the items in the nested form of the text, e.g. "none".
	/// </remarks>
	private static void AppendCollectionExpectation(StringBuilder sb, CollectionExpectationModel model, string name,
		string collection, string constraint, string summary, bool negated)
	{
		ClassModel classModel = model.Class;
		string quantifier = negated
			? $"{EnumerableQuantifier}.None({Grammars}.Nested)"
			: $"{EnumerableQuantifier}.All()";
		string resultType = ResultType(model, collection, $"global::aweXpect.Core.IThat<{collection}?>");
		sb.AppendLine("\t/// <summary>");
		AppendDocumentation(sb, summary);
		sb.AppendLine("\t/// </summary>");
		if (model.Remarks is { Length: > 0, } remarks)
		{
			sb.AppendLine("\t/// <remarks>");
			AppendDocumentation(sb, negated ? RenameReferences(remarks, classModel.Parameters) : remarks);
			sb.AppendLine("\t/// </remarks>");
		}

		sb.AppendLine("\t[global::aweXpect.Core.GuaranteesNotNull]");
		sb.Append('\t').Append(classModel.MethodAccessibility).Append(" static ").Append(resultType).Append(' ')
			.Append(name).Append(TypeParameters(model, null))
			.Append("(this global::aweXpect.Core.IThat<").Append(collection).Append("?> subject");
		foreach (ParameterModel parameter in classModel.Parameters.Values)
		{
			sb.Append(", ").Append(parameter.IsParams ? "params " : "").Append(parameter.Type).Append(' ')
				.Append(parameter.GetName(negated));
		}

		sb.AppendLine(")");
		AppendItemTypeConstraints(sb, model);
		sb.AppendLine("\t{");
		AppendNullChecks(sb, classModel.Parameters, negated);
		AppendOptions(sb, model);
		List<string> values = classModel.Parameters.Values.Select(p => p.GetName(negated)).ToList();
		if (model.Options is not null)
		{
			values.Add("__options");
		}

		int count = values.Count;
		string arguments = string.Concat(Enumerable.Range(0, count)
			.Select(i => count == 1 ? ", __state" : $", __state.Item{i + 1}"));
		string newConstraint =
			$"new {constraint}(__it, __grammars, {quantifier}, true{arguments}{OptionsParameterName(model, negated)})";
		sb.Append("\t\treturn new ").Append(resultType)
			.Append("(global::aweXpect.Core.Extending.ThatExtensions.Get(subject).ExpectationBuilder.AddConstraint(");
		switch (count)
		{
			case 0:
				sb.Append("(__it, __grammars) => ");
				break;
			case 1:
				sb.Append(values[0]).Append(", (__state, __it, __grammars) => ");
				break;
			default:
				sb.Append('(').Append(string.Join(", ", values)).Append("), (__state, __it, __grammars) => ");
				break;
		}

		sb.Append(newConstraint).AppendLine("),");
		sb.Append("\t\t\tsubject").Append(model.Options is null ? "" : ", __options").AppendLine(");");
		sb.AppendLine("\t}");
		sb.AppendLine();
	}

	/// <summary>
	///     Appends the constraints of all item types, separated by an empty line.
	/// </summary>
	private static void AppendConstraints(StringBuilder sb, CollectionExpectationModel model)
	{
		List<string> constraints = [];
		foreach (ItemModel item in model.Items.Values)
		{
			constraints.Add(WriteConstraint(model, item, SyncConstraint(item), TypeParameters(model, "TCollection"),
				$"global::aweXpect.Core.Extending.GeneratedCollectionConstraint<TCollection, {item.ItemType}>",
				$"{EnumerableType}<{item.ItemType}>?"));
			if (model.SupportsAsyncEnumerables)
			{
				constraints.Add(WriteConstraint(model, item, AsyncConstraint(item), TypeParameters(model, null),
					$"global::aweXpect.Core.Extending.GeneratedAsyncCollectionConstraint<{item.ItemType}>", null));
			}
		}

		for (int i = 0; i < constraints.Count; i++)
		{
			if (i > 0)
			{
				sb.AppendLine();
			}

			sb.Append(constraints[i]);
		}
	}

	/// <param name="sb">The source to append to.</param>
	/// <param name="model">The expectation.</param>
	/// <param name="items">The extended items.</param>
	/// <param name="collection">The type of the collection that the expectation continues with.</param>
	/// <param name="constraint">The constructed constraint.</param>
	/// <param name="structConstraint">
	///     The interface that a generic struct collection <c>TCollection</c> implements, or <see langword="null" /> when
	///     the method is not generic.
	/// </param>
	private static void AppendExpectation(StringBuilder sb, CollectionExpectationModel model, string items,
		string collection, string constraint, string? structConstraint)
	{
		ClassModel classModel = model.Class;
		string receiver = classModel.Parameters.Values.Any(p => p.Name == "items") ? "__items" : "items";
		string thatType = structConstraint is null ? collection + "?" : collection;
		string resultType = ResultType(model, collection, $"global::aweXpect.Core.IThat<{thatType}>");
		sb.AppendLine("\t/// <summary>");
		AppendDocumentation(sb, model.Summary ?? $"…{ToDocumentation(model.PluralText, classModel, false)}.");
		sb.AppendLine("\t/// </summary>");
		if (model.Remarks is { Length: > 0, } remarks)
		{
			sb.AppendLine("\t/// <remarks>");
			AppendDocumentation(sb, remarks);
			sb.AppendLine("\t/// </remarks>");
		}

		sb.Append('\t').Append(classModel.MethodAccessibility).Append(" static ").Append(resultType).Append(' ')
			.Append(model.Name).Append(TypeParameters(model, structConstraint is null ? null : "TCollection"))
			.Append("(this ").Append(items).Append(' ').Append(receiver);
		foreach (ParameterModel parameter in classModel.Parameters.Values)
		{
			sb.Append(", ").Append(parameter.IsParams ? "params " : "").Append(parameter.Type).Append(' ')
				.Append(parameter.Name);
		}

		sb.AppendLine(")");
		if (structConstraint is not null)
		{
			sb.Append("\t\twhere TCollection : struct, ").AppendLine(structConstraint);
		}

		AppendItemTypeConstraints(sb, model);
		sb.AppendLine("\t{");
		AppendNullChecks(sb, classModel.Parameters, false);
		AppendOptions(sb, model);
		List<string> values = classModel.Parameters.Values.Select(p => p.Name).ToList();
		if (model.Options is not null)
		{
			values.Add("__options");
		}

		int count = values.Count;
		string state = count == 0
			? $"{receiver}.Quantifier"
			: $"({receiver}.Quantifier, {string.Join(", ", values)})";
		string arguments = (count == 0 ? "__state" : "__state.Item1") +
		                   (model.HasCollectionExpectations ? ", false" : "") +
		                   string.Concat(Enumerable.Range(0, count).Select(i => $", __state.Item{i + 2}"));
		sb.Append("\t\treturn new ").Append(resultType)
			.Append("(global::aweXpect.Core.Extending.ThatExtensions.Get(").Append(receiver)
			.Append(".Subject).ExpectationBuilder.AddConstraint(")
			.Append(state).Append(", (__state, __it, __grammars) => new ").Append(constraint)
			.Append("(__it, __grammars, ").Append(arguments).Append(OptionsParameterName(model, false)).AppendLine(")),");
		sb.Append("\t\t\t").Append(receiver).Append(".Subject").Append(model.Options is null ? "" : ", __options")
			.AppendLine(");");
		sb.AppendLine("\t}");
		sb.AppendLine();
	}

	/// <summary>
	///     The plain result, or with options the result that configures them.
	/// </summary>
	private static string ResultType(CollectionExpectationModel model, string collection, string that)
		=> model.Options is { } options
			? $"{options.ResultType}<{collection}, {that}>"
			: $"global::aweXpect.Results.AndOrResult<{collection}, {that}>";

	/// <summary>
	///     Creates the holder of the options with their default value, which the result changes.
	/// </summary>
	private static void AppendOptions(StringBuilder sb, CollectionExpectationModel model)
	{
		if (model.Options is { } options)
		{
			string holder = OptionsHolder(options);
			sb.Append("\t\t").Append(holder).Append(" __options = new ").Append(holder).Append('(')
				.Append(options.OptionsType).AppendLine(".Default);");
		}
	}

	/// <summary>
	///     The name of the parameter that the options compare with, as the expectation names it, so that an unusable
	///     pattern is reported against it, or nothing without options.
	/// </summary>
	private static string OptionsParameterName(CollectionExpectationModel model, bool negated)
		=> model.Options is { } options
			? ", " + Literal(model.Class.Parameters.Values[options.PatternParameterIndex].GetName(negated).TrimStart('@'))
			: "";

	private static string OptionsHolder(OptionsModel options)
		=> $"global::aweXpect.Core.OptionsHolder<{options.OptionsType}>";

	private static string SyncConstraint(ItemModel item) => $"{item.ConstraintPrefix}ItemsConstraint";

	private static string AsyncConstraint(ItemModel item) => $"{item.ConstraintPrefix}AsyncItemsConstraint";

	/// <param name="model">The expectation.</param>
	/// <param name="item">The item type.</param>
	/// <param name="constraintName">The name of the constraint class.</param>
	/// <param name="typeParameters">The type parameters of the constraint class.</param>
	/// <param name="baseType">The base class of the constraint class.</param>
	/// <param name="collectionConstraint">
	///     The interface that the generic collection <c>TCollection</c> implements, or <see langword="null" /> when the
	///     class is not generic.
	/// </param>
	private static string WriteConstraint(CollectionExpectationModel model, ItemModel item, string constraintName,
		string typeParameters, string baseType, string? collectionConstraint)
	{
		ClassModel classModel = model.Class;
		StringBuilder sb = new();
		sb.Append("\tprivate sealed class ").Append(constraintName).Append(typeParameters).Append(" : ")
			.AppendLine(baseType);
		if (collectionConstraint is not null)
		{
			sb.Append("\t\twhere TCollection : ").AppendLine(collectionConstraint);
		}

		AppendItemTypeConstraints(sb, model);
		sb.AppendLine("\t{");
		for (int i = 0; i < classModel.Parameters.Count; i++)
		{
			sb.Append("\t\tprivate readonly ").Append(classModel.Parameters.Values[i].Type).Append(" _p").Append(i)
				.AppendLine(";");
		}

		if (model.Options is { } options)
		{
			sb.Append("\t\tprivate readonly ").Append(OptionsHolder(options)).AppendLine(" _options;");
			sb.AppendLine("\t\tprivate readonly string _optionsParameterName;");
			sb.Append("\t\tprivate ").Append(options.OptionsType).AppendLine("? _evaluationOptions;");
		}

		if (classModel.Parameters.Count > 0 || model.Options is not null)
		{
			sb.AppendLine();
		}

		sb.Append("\t\tpublic ").Append(constraintName).Append("(string it, ").Append(Grammars)
			.Append(" grammars, ").Append(EnumerableQuantifier).Append(" quantifier")
			.Append(model.HasCollectionExpectations ? ", bool isOnCollection" : "");
		for (int i = 0; i < classModel.Parameters.Count; i++)
		{
			sb.Append(", ").Append(classModel.Parameters.Values[i].Type).Append(" p").Append(i);
		}

		if (model.Options is not null)
		{
			sb.Append(", ").Append(OptionsHolder(model.Options.Value)).Append(" options, string optionsParameterName");
		}

		sb.AppendLine(")");
		sb.Append("\t\t\t: base(it, grammars, quantifier").Append(model.HasCollectionExpectations ? ", isOnCollection" : "")
			.AppendLine(")");
		sb.AppendLine("\t\t{");
		for (int i = 0; i < classModel.Parameters.Count; i++)
		{
			sb.Append("\t\t\t_p").Append(i).Append(" = p").Append(i).AppendLine(";");
		}

		if (model.Options is not null)
		{
			sb.AppendLine("\t\t\t_options = options;");
			sb.AppendLine("\t\t\t_optionsParameterName = optionsParameterName;");
		}

		sb.AppendLine("\t\t}");
		sb.AppendLine();
		if (model.Options is not null)
		{
			AppendOptionsEvaluation(sb, model.Options.Value);
		}

		sb.Append("\t\tprotected override string Verb => ").Append(Literal(model.Verb)).AppendLine(";");
		sb.AppendLine();
		AppendIsMatch(sb, model, item);
		AppendItemExpectation(sb, model);
		if (model.FormattedItem is { } formattedItem)
		{
			AppendFormatItems(sb, model, item, formattedItem);
		}

		sb.AppendLine("\t}");
		return sb.ToString();
	}

	/// <remarks>
	///     A <see langword="null" /> item of the nullable overload of a value type stays <see langword="null" />, as the
	///     method takes the value type.
	/// </remarks>
	private static void AppendFormatItems(StringBuilder sb, CollectionExpectationModel model, ItemModel item,
		string formattedItem)
	{
		string call = $"{Owner(model.Class)}.{formattedItem}({item.ItemArgument})";
		string value = item.ItemArgument == "item" ? $"(object?){call}" : $"item is null ? null : (object?){call}";
		sb.AppendLine();
		sb.Append("\t\tprotected override string FormatItems(").Append(EnumerableType).Append('<')
			.Append(item.ItemType).Append("> items, ").Append(FormattingOptions).AppendLine(" options)");
		sb.Append("\t\t\t=> ").Append(ValueFormatters).Append(".Format<object?>(").Append(Formatter)
			.Append(", global::System.Linq.Enumerable.Select<").Append(item.ItemType)
			.Append(", object?>(items, item => ").Append(value).AppendLine("), options);");
	}

	/// <remarks>
	///     The expected value is validated before any item is read, so that an unusable pattern is rejected for every
	///     collection, also an empty one.
	/// </remarks>
	private static void AppendOptionsEvaluation(StringBuilder sb, OptionsModel options)
	{
		sb.AppendLine("\t\tprotected override void OnEvaluating(global::aweXpect.Core.EvaluationContext.IEvaluationContext context, global::System.Threading.CancellationToken cancellationToken)");
		sb.AppendLine("\t\t{");
		sb.AppendLine("\t\t\t_evaluationOptions = _options.Value.ForEvaluation(context, cancellationToken);");
		sb.Append("\t\t\t_evaluationOptions.ValidateExpected(_p").Append(options.PatternParameterIndex)
			.AppendLine(", _optionsParameterName);");
		sb.AppendLine("\t\t}");
		sb.AppendLine();
		sb.AppendLine("\t\tpublic override void AppendContexts(global::aweXpect.Core.ResultContextCollector contexts)");
		sb.AppendLine("\t\t{");
		sb.AppendLine("\t\t\tbase.AppendContexts(contexts);");
		sb.AppendLine("\t\t\t(_evaluationOptions ?? _options.Value).AppendContexts(contexts);");
		sb.AppendLine("\t\t}");
		sb.AppendLine();
	}

	/// <summary>
	///     The arguments of the predicate after the item, with the cancellation token and the options of the evaluation
	///     at their positions.
	/// </summary>
	private static string GetPredicateArguments(CollectionExpectationModel model)
	{
		List<string> arguments = Enumerable.Range(0, model.Class.Parameters.Count).Select(i => $"_p{i}").ToList();
		List<(int Index, string Argument)> inserted = [];
		if (model.CancellationTokenIndex >= 0)
		{
			inserted.Add((model.CancellationTokenIndex, "cancellationToken"));
		}

		if (model.Options is { } options)
		{
			inserted.Add((options.ArgumentIndex, "(_evaluationOptions ?? _options.Value)"));
		}

		foreach ((int index, string argument) in inserted.OrderBy(x => x.Index))
		{
			arguments.Insert(index, argument);
		}

		return string.Concat(arguments.Select(argument => ", " + argument));
	}

	private static string Owner(ClassModel classModel)
		=> classModel.Namespace is null
			? $"global::{classModel.ClassName}"
			: $"global::{classModel.Namespace}.{classModel.ClassName}";

	private static void AppendIsMatch(StringBuilder sb, CollectionExpectationModel model, ItemModel item)
	{
		ClassModel classModel = model.Class;
		string call = $"{Owner(classModel)}.{classModel.PredicateName}{TypeParameters(model, null)}({item.ItemArgument}"
		              + $"{GetPredicateArguments(model)})";
		string result = $"{ExpectationWriter.ValueTask}<{PredicateResult}>";
		// An asynchronous bool is awaited, as only the result itself converts to a PredicateResult.
		bool awaitsBool = model.PredicateKind != PredicateKind.Synchronous && !model.ReturnsPredicateResult;
		string nullItem = model.NullItemFailsBothWays
			? $"{PredicateResult}.FailureBothWays({Literal("was <null>")})"
			: "false";
		string match = model.PredicateKind switch
		{
			_ when awaitsBool && item.FailsOnNull => $"item is null ? {nullItem} : await {call}",
			_ when awaitsBool => $"await {call}",
			PredicateKind.Synchronous when item.FailsOnNull && !model.ReturnsPredicateResult &&
			                               !model.NullItemFailsBothWays
				=> $"new {result}(!(item is null) && {call})",
			PredicateKind.Synchronous or PredicateKind.Task when item.FailsOnNull
				=> $"item is null ? new {result}({nullItem}) : new {result}({call})",
			PredicateKind.Synchronous or PredicateKind.Task => $"new {result}({call})",
			_ when item.FailsOnNull => $"item is null ? new {result}({nullItem}) : {call}",
			_ => call,
		};
		sb.Append("\t\tprotected override ").Append(awaitsBool ? "async " : "").Append(result).Append(" IsMatch(")
			.Append(item.ItemType).AppendLine(" item, global::System.Threading.CancellationToken cancellationToken)");
		sb.Append("\t\t\t=> ").Append(match).AppendLine(";");
		sb.AppendLine();
	}

	private static void AppendItemExpectation(StringBuilder sb, CollectionExpectationModel model)
	{
		sb.Append("\t\tprotected override void AppendItemExpectation(").Append(ExpectationWriter.StringBuilder).Append(" stringBuilder, ")
			.Append(Grammars).AppendLine(" grammars, string? indentation)");
		sb.AppendLine("\t\t{");
		sb.Append("\t\t\tif (").Append(GrammarsExtensions).AppendLine(".IsPlural(grammars))");
		sb.AppendLine("\t\t\t{");
		AppendTextParts(sb, model.PluralText, model.Options);
		sb.AppendLine("\t\t\t}");
		sb.AppendLine("\t\t\telse");
		sb.AppendLine("\t\t\t{");
		AppendTextParts(sb, model.Text, model.Options);
		sb.AppendLine("\t\t\t}");
		sb.AppendLine("\t\t}");
	}

	/// <remarks>
	///     The options write the parameter that they compare with, e.g. <c>starts with "foo" ignoring case</c>.
	/// </remarks>
	private static void AppendTextParts(StringBuilder sb, EquatableArray<TextPart> parts, OptionsModel? options)
	{
		foreach (TextPart part in parts.Values)
		{
			if (part.Text is null && part.ParameterIndex == options?.PatternParameterIndex)
			{
				sb.Append("\t\t\t\tstringBuilder.Append(_options.Value.GetExpectation(_p").Append(part.ParameterIndex)
					.AppendLine(", grammars));");
			}
			else if (part.Text is null)
			{
				sb.Append("\t\t\t\t").Append(ValueFormatters).Append(".Format(").Append(Formatter)
					.Append(", stringBuilder, _p").Append(part.ParameterIndex).AppendLine(");");
			}
			else
			{
				sb.Append("\t\t\t\tstringBuilder.Append(").Append(Literal(part.Text)).AppendLine(");");
			}
		}
	}

	private static string ToDocumentation(EquatableArray<TextPart> parts, ClassModel classModel, bool negated)
		=> string.Concat(parts.Values.Select(part => part.Text is null
			? $"<paramref name=\"{classModel.Parameters.Values[part.ParameterIndex].GetName(negated).TrimStart('@')}\" />"
			: EscapeXml(part.Text)));

	/// <summary>
	///     The <paramref name="text" /> with every <c>&lt;paramref&gt;</c> to a parameter renamed to its negated name.
	/// </summary>
	private static string RenameReferences(string text, EquatableArray<ParameterModel> parameters)
		=> parameters.Values.Where(p => p.NegatedName != p.Name).Aggregate(text, (current, p)
			=> current.Replace($"<paramref name=\"{p.Name.TrimStart('@')}\"",
				$"<paramref name=\"{p.NegatedName.TrimStart('@')}\""));
}
