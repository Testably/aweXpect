using System.Text;
using static aweXpect.Core.Generators.ExpectationWriter;

namespace aweXpect.Core.Generators;

/// <summary>
///     Writes the source of a <see cref="CollectionExpectationModel" />.
/// </summary>
/// <remarks>
///     Every type is fully qualified, so that the generated code binds the same in any namespace and without the usings
///     of the declaring file.
/// </remarks>
internal static class CollectionExpectationWriter
{
	private const string EnumerableType = "global::System.Collections.Generic.IEnumerable";
	private const string AsyncEnumerableType = "global::System.Collections.Generic.IAsyncEnumerable";

	public static string Write(CollectionExpectationModel model)
	{
		ClassModel classModel = model.Class;
		StringBuilder sb = new();
		sb.AppendLine("// <auto-generated/>");
		sb.AppendLine("#nullable enable");
		sb.AppendLine();
		AppendUsings(sb, classModel.Usings);
		if (classModel.Namespace is not null)
		{
			sb.Append("namespace ").AppendLine(classModel.Namespace);
			sb.AppendLine("{");
			AppendUsings(sb, classModel.NamespaceUsings);
		}

		sb.Append(classModel.ClassAccessibility).Append(" static partial class ").AppendLine(classModel.ClassName);
		sb.AppendLine("{");
		foreach (ItemModel item in model.Items.Values)
		{
			AppendExpectations(sb, model, item);
		}

		AppendConstraints(sb, model);
		sb.AppendLine("}");
		if (classModel.Namespace is not null)
		{
			sb.AppendLine("}");
		}

		return sb.ToString();
	}

	/// <summary>
	///     Appends the expectations on every kind of collection that holds the <paramref name="item" />.
	/// </summary>
	private static void AppendExpectations(StringBuilder sb, CollectionExpectationModel model, ItemModel item)
	{
		string elements = item.IsString
			? "global::aweXpect.IEnumerableStringElements"
			: $"global::aweXpect.IEnumerableElements<{item.ItemType}>";
		AppendExpectation(sb, model, elements, $"{EnumerableType}<{item.ItemType}>",
			$"{SyncConstraint(item)}<{EnumerableType}<{item.ItemType}>?>", null);

		string structElements = item.IsString
			? "global::aweXpect.IStructEnumerableStringElements<TEnumerable>"
			: $"global::aweXpect.IStructEnumerableElements<TEnumerable, {item.ItemType}>";
		AppendExpectation(sb, model, structElements, "TEnumerable",
			$"{SyncConstraint(item)}<TEnumerable>", $"{EnumerableType}<{item.ItemType}>");

		if (model.SupportsAsyncEnumerables)
		{
			string asyncElements = item.IsString
				? "global::aweXpect.IAsyncEnumerableStringElements"
				: $"global::aweXpect.IAsyncEnumerableElements<{item.ItemType}>";
			AppendExpectation(sb, model, asyncElements, $"{AsyncEnumerableType}<{item.ItemType}>",
				AsyncConstraint(item), null);
		}
	}

	/// <summary>
	///     Appends the constraints of all item types, separated by an empty line.
	/// </summary>
	private static void AppendConstraints(StringBuilder sb, CollectionExpectationModel model)
	{
		List<string> constraints = [];
		foreach (ItemModel item in model.Items.Values)
		{
			constraints.Add(WriteConstraint(model, item, SyncConstraint(item), "<TCollection>",
				$"global::aweXpect.Core.Extending.GeneratedCollectionConstraint<TCollection, {item.ItemType}>",
				$"{EnumerableType}<{item.ItemType}>?"));
			if (model.SupportsAsyncEnumerables)
			{
				constraints.Add(WriteConstraint(model, item, AsyncConstraint(item), "",
					$"global::aweXpect.Core.Extending.GeneratedAsyncCollectionConstraint<{item.ItemType}>", null));
			}
		}

		for (int i = 0; i < constraints.Count; i++)
		{
			if (i > 0)
			{
				sb.AppendLine();
			}

			sb.Append(constraints[i]);
		}
	}

	/// <param name="sb">The source to append to.</param>
	/// <param name="model">The expectation.</param>
	/// <param name="elements">The extended elements.</param>
	/// <param name="collection">The type of the collection that the expectation continues with.</param>
	/// <param name="constraint">The constructed constraint.</param>
	/// <param name="structConstraint">
	///     The interface that a generic struct collection <c>TEnumerable</c> implements, or <see langword="null" /> when
	///     the method is not generic.
	/// </param>
	private static void AppendExpectation(StringBuilder sb, CollectionExpectationModel model, string elements,
		string collection, string constraint, string? structConstraint)
	{
		ClassModel classModel = model.Class;
		string thatType = structConstraint is null ? collection + "?" : collection;
		string resultType =
			$"global::aweXpect.Results.AndOrResult<{collection}, global::aweXpect.Core.IThat<{thatType}>>";
		sb.AppendLine("\t/// <summary>");
		AppendDocumentation(sb, model.Summary ?? $"…{ToDocumentation(model.PluralText, classModel)}.");
		sb.AppendLine("\t/// </summary>");
		if (model.Remarks is { Length: > 0, } remarks)
		{
			sb.AppendLine("\t/// <remarks>");
			AppendDocumentation(sb, remarks);
			sb.AppendLine("\t/// </remarks>");
		}

		sb.Append('\t').Append(classModel.MethodAccessibility).Append(" static ").Append(resultType).Append(' ')
			.Append(model.Name).Append(structConstraint is null ? "" : "<TEnumerable>")
			.Append("(this ").Append(elements).Append(" elements");
		foreach (ParameterModel parameter in classModel.Parameters.Values)
		{
			sb.Append(", ").Append(parameter.IsParams ? "params " : "").Append(parameter.Type).Append(' ')
				.Append(parameter.Name);
		}

		sb.AppendLine(")");
		if (structConstraint is not null)
		{
			sb.Append("\t\twhere TEnumerable : struct, ").AppendLine(structConstraint);
		}

		sb.AppendLine("\t{");
		AppendNullChecks(sb, classModel.Parameters);
		int count = classModel.Parameters.Count;
		string state = count == 0
			? "elements.Quantifier"
			: $"(elements.Quantifier, {string.Join(", ", classModel.Parameters.Values.Select(p => p.Name))})";
		string arguments = count == 0
			? "__state"
			: string.Concat(Enumerable.Range(0, count + 1).Select(i => (i == 0 ? "" : ", ") + $"__state.Item{i + 1}"));
		sb.Append("\t\treturn new ").Append(resultType)
			.Append("(global::aweXpect.Core.Extending.ThatExtensions.Get(elements.Subject).ExpectationBuilder.AddConstraint(")
			.Append(state).Append(", (__state, __it, __grammars) => new ").Append(constraint)
			.Append("(__it, __grammars, ").Append(arguments).AppendLine(")),");
		sb.AppendLine("\t\t\telements.Subject);");
		sb.AppendLine("\t}");
		sb.AppendLine();
	}

	private static string SyncConstraint(ItemModel item) => $"{item.ConstraintPrefix}ElementsConstraint";

	private static string AsyncConstraint(ItemModel item) => $"{item.ConstraintPrefix}AsyncElementsConstraint";

	/// <param name="model">The expectation.</param>
	/// <param name="item">The item type.</param>
	/// <param name="constraintName">The name of the constraint class.</param>
	/// <param name="typeParameters">The type parameters of the constraint class.</param>
	/// <param name="baseType">The base class of the constraint class.</param>
	/// <param name="collectionConstraint">
	///     The interface that the generic collection <c>TCollection</c> implements, or <see langword="null" /> when the
	///     class is not generic.
	/// </param>
	private static string WriteConstraint(CollectionExpectationModel model, ItemModel item, string constraintName,
		string typeParameters, string baseType, string? collectionConstraint)
	{
		ClassModel classModel = model.Class;
		StringBuilder sb = new();
		sb.Append("\tprivate sealed class ").Append(constraintName).Append(typeParameters).Append(" : ")
			.AppendLine(baseType);
		if (collectionConstraint is not null)
		{
			sb.Append("\t\twhere TCollection : ").AppendLine(collectionConstraint);
		}

		sb.AppendLine("\t{");
		for (int i = 0; i < classModel.Parameters.Count; i++)
		{
			sb.Append("\t\tprivate readonly ").Append(classModel.Parameters.Values[i].Type).Append(" _p").Append(i)
				.AppendLine(";");
		}

		if (classModel.Parameters.Count > 0)
		{
			sb.AppendLine();
		}

		sb.Append("\t\tpublic ").Append(constraintName).Append("(string it, ").Append(Grammars)
			.Append(" grammars, global::aweXpect.Options.EnumerableQuantifier quantifier");
		for (int i = 0; i < classModel.Parameters.Count; i++)
		{
			sb.Append(", ").Append(classModel.Parameters.Values[i].Type).Append(" p").Append(i);
		}

		sb.AppendLine(")");
		sb.AppendLine("\t\t\t: base(it, grammars, quantifier)");
		sb.AppendLine("\t\t{");
		for (int i = 0; i < classModel.Parameters.Count; i++)
		{
			sb.Append("\t\t\t_p").Append(i).Append(" = p").Append(i).AppendLine(";");
		}

		sb.AppendLine("\t\t}");
		sb.AppendLine();
		sb.Append("\t\tprotected override string Verb => ").Append(Literal(model.Verb)).AppendLine(";");
		sb.AppendLine();
		AppendIsMatch(sb, model, item);
		AppendItemExpectation(sb, model);
		sb.AppendLine("\t}");
		return sb.ToString();
	}

	private static void AppendIsMatch(StringBuilder sb, CollectionExpectationModel model, ItemModel item)
	{
		ClassModel classModel = model.Class;
		string owner = classModel.Namespace is null
			? $"global::{classModel.ClassName}"
			: $"global::{classModel.Namespace}.{classModel.ClassName}";
		string call = $"{owner}.{classModel.PredicateName}({item.ItemArgument}"
		              + $"{GetArguments(classModel.Parameters.Count, model.CancellationTokenIndex)})";
		string result = $"{ExpectationWriter.ValueTask}<{PredicateResult}>";
		// An asynchronous bool is awaited, as only the result itself converts to a PredicateResult.
		bool awaitsBool = model.PredicateKind != PredicateKind.Synchronous && !model.ReturnsPredicateResult;
		string match = model.PredicateKind switch
		{
			_ when awaitsBool && item.FailsOnNull => $"item is null ? false : await {call}",
			_ when awaitsBool => $"await {call}",
			PredicateKind.Synchronous when item.FailsOnNull && !model.ReturnsPredicateResult
				=> $"new {result}(!(item is null) && {call})",
			PredicateKind.Synchronous or PredicateKind.Task when item.FailsOnNull
				=> $"item is null ? new {result}(false) : new {result}({call})",
			PredicateKind.Synchronous or PredicateKind.Task => $"new {result}({call})",
			_ when item.FailsOnNull => $"item is null ? new {result}(false) : {call}",
			_ => call,
		};
		sb.Append("\t\tprotected override ").Append(awaitsBool ? "async " : "").Append(result).Append(" IsMatch(")
			.Append(item.ItemType).AppendLine(" item, global::System.Threading.CancellationToken cancellationToken)");
		sb.Append("\t\t\t=> ").Append(match).AppendLine(";");
		sb.AppendLine();
	}

	private static void AppendItemExpectation(StringBuilder sb, CollectionExpectationModel model)
	{
		sb.Append("\t\tprotected override void AppendItemExpectation(").Append(ExpectationWriter.StringBuilder).Append(" stringBuilder, ")
			.Append(Grammars).AppendLine(" grammars, string? indentation)");
		sb.AppendLine("\t\t{");
		sb.Append("\t\t\tif (").Append(GrammarsExtensions).AppendLine(".IsPlural(grammars))");
		sb.AppendLine("\t\t\t{");
		AppendTextParts(sb, model.PluralText);
		sb.AppendLine("\t\t\t}");
		sb.AppendLine("\t\t\telse");
		sb.AppendLine("\t\t\t{");
		AppendTextParts(sb, model.Text);
		sb.AppendLine("\t\t\t}");
		sb.AppendLine("\t\t}");
	}

	private static void AppendTextParts(StringBuilder sb, EquatableArray<TextPart> parts)
	{
		foreach (TextPart part in parts.Values)
		{
			if (part.Text is null)
			{
				sb.Append("\t\t\t\t").Append(ValueFormatters).Append(".Format(").Append(Formatter)
					.Append(", stringBuilder, _p").Append(part.ParameterIndex).AppendLine(");");
			}
			else
			{
				sb.Append("\t\t\t\tstringBuilder.Append(").Append(Literal(part.Text)).AppendLine(");");
			}
		}
	}

	private static string ToDocumentation(EquatableArray<TextPart> parts, ClassModel classModel)
		=> string.Concat(parts.Values.Select(part => part.Text is null
			? $"<paramref name=\"{classModel.Parameters.Values[part.ParameterIndex].Name.TrimStart('@')}\" />"
			: EscapeXml(part.Text)));
}
