using aweXpect.Core;
using aweXpect.Options;
using aweXpect.Results;

namespace aweXpect.Web.Results;

/// <summary>
///     Result for handling additional expectations on problem details.
/// </summary>
public class ProblemDetailsResult<TType, TThat>
	: ProblemDetailsResult<TType, TThat, ProblemDetailsResult<TType, TThat>>
{
	internal ProblemDetailsResult(
		ExpectationBuilder expectationBuilder,
		TThat returnValue,
		ProblemDetailsOptions options)
		: base(expectationBuilder, returnValue, options)
	{
	}

	/// <summary>
	///     In addition to a <see cref="ProblemDetailsResult{TType,TThat}" /> allows specifying string equality settings
	///     and the match type, e.g. via <c>AsWildcard()</c>, for the last specified string value.
	/// </summary>
	public class String
		: ProblemDetailsResult<TType, TThat, String>,
			IOptionsProvider<StringEqualityOptions>,
			IStringMatchTypeOptions
	{
		private readonly OptionsHolder<StringEqualityOptions> _stringEqualityOptions;

		internal String(
			ExpectationBuilder expectationBuilder,
			TThat returnValue,
			OptionsHolder<StringEqualityOptions> stringEqualityOptions,
			ProblemDetailsOptions options)
			: base(expectationBuilder, returnValue, options)
		{
			_stringEqualityOptions = stringEqualityOptions;
		}

		/// <inheritdoc cref="IOptionsProvider{TOptions}.Options" />
		OptionsHolder<StringEqualityOptions> IOptionsProvider<StringEqualityOptions>.Options => _stringEqualityOptions;
	}
}

/// <summary>
///     Result for handling additional expectations on problem details, which keeps the <typeparamref name="TSelf" />
///     result after <c>Because</c>.
/// </summary>
/// <remarks>
///     Shares the members of <see cref="ProblemDetailsResult{TType,TThat}" /> and its
///     <see cref="ProblemDetailsResult{TType,TThat}.String" /> result.
/// </remarks>
public class ProblemDetailsResult<TType, TThat, TSelf>
	: AndOrResult<TType, TThat, TSelf>
	where TSelf : ProblemDetailsResult<TType, TThat, TSelf>
{
	private readonly ExpectationBuilder _expectationBuilder;
	private readonly ProblemDetailsOptions _options;
	private readonly TThat _returnValue;

	internal ProblemDetailsResult(
		ExpectationBuilder expectationBuilder,
		TThat returnValue,
		ProblemDetailsOptions options)
		: base(expectationBuilder, returnValue)
	{
		_expectationBuilder = expectationBuilder;
		_returnValue = returnValue;
		_options = options;
	}

	/// <summary>
	///     Verify that the title of the problem details object matches the <paramref name="expected" /> title.
	/// </summary>
	/// <remarks>
	///     Title:
	///     A short, human-readable summary of the problem type. It SHOULD NOT change from occurrence to occurrence of the
	///     problem, except for purposes of localization(e.g., using proactive content negotiation;
	///     <see href="https://datatracker.ietf.org/doc/html/rfc7231#section-3.4" />).
	/// </remarks>
	public ProblemDetailsResult<TType, TThat>.String WithTitle(string expected)
		=> new(_expectationBuilder, _returnValue, _options.WithTitle(expected), _options);

	/// <summary>
	///     Verify that the status of the problem details object matches the <paramref name="expected" /> status.
	/// </summary>
	/// <remarks>
	///     Status:
	///     The HTTP status code (<see href="https://datatracker.ietf.org/doc/html/rfc7231#section-6" />) generated by the
	///     origin server for this occurrence of the problem.
	/// </remarks>
	public ProblemDetailsResult<TType, TThat> WithStatus(int expected)
	{
		_options.WithStatus(expected);
		return new ProblemDetailsResult<TType, TThat>(_expectationBuilder, _returnValue, _options);
	}

	/// <summary>
	///     Verify that the detail of the problem details object matches the <paramref name="expected" /> detail.
	/// </summary>
	/// <remarks>
	///     Detail:
	///     A human-readable explanation specific to this occurrence of the problem.
	/// </remarks>
	public ProblemDetailsResult<TType, TThat>.String WithDetail(string expected)
		=> new(_expectationBuilder, _returnValue, _options.WithDetail(expected), _options);

	/// <summary>
	///     Verify that the instance of the problem details object matches the <paramref name="expected" /> instance.
	/// </summary>
	/// <remarks>
	///     Instance:
	///     A URI reference that identifies the specific occurrence of the problem.  It may or may not yield further
	///     information if dereferenced.
	/// </remarks>
	public ProblemDetailsResult<TType, TThat>.String WithInstance(string expected)
		=> new(_expectationBuilder, _returnValue, _options.WithInstance(expected), _options);
}
