using System;
using System.Collections.Generic;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using aweXpect.Core;
using aweXpect.Core.EvaluationContext;
using aweXpect.Helpers;
using aweXpect.Options;

namespace aweXpect.Web.Results;

/// <summary>
///     Options for <see cref="ProblemDetailsResult{TType,TThat}" />.
/// </summary>
internal class ProblemDetailsOptions
{
	private readonly List<Func<string>> _parts = new();

	/// <remarks>
	///     The options of a value are only created when the value is expected, as most expectations specify only some.
	/// </remarks>
	private StringEqualityOptions? _detailOptions;

	private StringEqualityOptions? _instanceOptions;
	private StringEqualityOptions? _titleOptions;

	/// <summary>
	///     The title of a problem details object.
	///     <seealso href="https://learn.microsoft.com/en-us/dotnet/api/microsoft.aspnetcore.mvc.problemdetails.title" />
	/// </summary>
	/// <remarks>
	///     A short, human-readable summary of the problem type. It SHOULD NOT change from occurrence to occurrence of the
	///     problem, except for purposes of localization(e.g., using proactive content negotiation;
	///     <see href="https://datatracker.ietf.org/doc/html/rfc7231#section-3.4" />).
	/// </remarks>
	public string? Title { get; private set; }

	/// <summary>
	///     The status of a problem details object.
	///     <seealso href="https://learn.microsoft.com/en-us/dotnet/api/microsoft.aspnetcore.mvc.problemdetails.status" />
	/// </summary>
	/// <remarks>
	///     The HTTP status code (<see href="https://datatracker.ietf.org/doc/html/rfc7231#section-6" />) generated by the
	///     origin server for this occurrence of the problem.
	/// </remarks>
	public int? Status { get; private set; }

	/// <summary>
	///     The detail of a problem details object.
	///     <seealso href="https://learn.microsoft.com/en-us/dotnet/api/microsoft.aspnetcore.mvc.problemdetails.instance" />
	/// </summary>
	/// <remarks>
	///     A human-readable explanation specific to this occurrence of the problem.
	/// </remarks>
	public string? Detail { get; private set; }

	/// <summary>
	///     The instance of a problem details object.
	///     <seealso href="https://learn.microsoft.com/en-us/dotnet/api/microsoft.aspnetcore.mvc.problemdetails.instance" />
	/// </summary>
	/// <remarks>
	///     A URI reference that identifies the specific occurrence of the problem.  It may or may not yield further
	///     information if dereferenced.
	/// </remarks>
	public string? Instance { get; private set; }

	/// <summary>
	///     Sets the expected <paramref name="title" />.
	/// </summary>
	/// <remarks>
	///     A later title replaces the earlier one together with its options, and keeps its place in the description.
	/// </remarks>
	public StringEqualityOptions WithTitle(string title)
	{
		ThrowHelper.ThrowIfNull(title, nameof(title));
		bool isFirst = Title is null;
		Title = title;
		StringEqualityOptions titleOptions = new("title");
		_titleOptions = titleOptions;
		if (isFirst)
		{
			_parts.Add(() => Describe("title", Title!, _titleOptions!));
		}

		return titleOptions;
	}

	/// <summary>
	///     Sets the expected <paramref name="status" />.
	/// </summary>
	/// <remarks>
	///     A later status replaces the earlier one, and keeps its place in the description.
	/// </remarks>
	public void WithStatus(int status)
	{
		bool isFirst = Status is null;
		Status = status;
		if (isFirst)
		{
			_parts.Add(() => $"status {Formatter.Format(Status)}");
		}
	}

	/// <summary>
	///     Sets the expected <paramref name="detail" />.
	/// </summary>
	/// <remarks>
	///     A later detail replaces the earlier one together with its options, and keeps its place in the description.
	/// </remarks>
	public StringEqualityOptions WithDetail(string detail)
	{
		ThrowHelper.ThrowIfNull(detail, nameof(detail));
		bool isFirst = Detail is null;
		Detail = detail;
		StringEqualityOptions detailOptions = new("detail");
		_detailOptions = detailOptions;
		if (isFirst)
		{
			_parts.Add(() => Describe("detail", Detail!, _detailOptions!));
		}

		return detailOptions;
	}

	/// <summary>
	///     Sets the expected <paramref name="instance" />.
	/// </summary>
	/// <remarks>
	///     A later instance replaces the earlier one together with its options, and keeps its place in the description.
	/// </remarks>
	public StringEqualityOptions WithInstance(string instance)
	{
		ThrowHelper.ThrowIfNull(instance, nameof(instance));
		bool isFirst = Instance is null;
		Instance = instance;
		StringEqualityOptions instanceOptions = new("instance");
		_instanceOptions = instanceOptions;
		if (isFirst)
		{
			_parts.Add(() => Describe("instance", Instance!, _instanceOptions!));
		}

		return instanceOptions;
	}

	/// <summary>
	///     Describes the <paramref name="expected" /> value of the <paramref name="member" />, e.g. <c>title "foo"</c>.
	/// </summary>
	/// <remarks>
	///     A match type that inspects the value, e.g. a wildcard or a prefix, is described by its phrase, e.g.
	///     <c>title matching "foo*"</c>, as the expected value is not the value the member has to be equal to.
	/// </remarks>
	internal static string Describe(string member, string expected, StringEqualityOptions options)
		=> options.InspectsSubject
			? $"{member} {options.GetExpectation(expected, ExpectationGrammars.None)}"
			: $"{member} {Formatter.Format(expected)}{options}";

	/// <summary>
	///     Returns the options to use for the comparisons of the evaluation in the <paramref name="context" />.
	/// </summary>
	public ProblemDetailsOptions ForEvaluation(IEvaluationContext context, CancellationToken cancellationToken)
	{
		StringEqualityOptions? titleOptions = _titleOptions?.ForEvaluation(context, cancellationToken);
		StringEqualityOptions? detailOptions = _detailOptions?.ForEvaluation(context, cancellationToken);
		StringEqualityOptions? instanceOptions = _instanceOptions?.ForEvaluation(context, cancellationToken);
		if (ReferenceEquals(titleOptions, _titleOptions) && ReferenceEquals(detailOptions, _detailOptions) &&
		    ReferenceEquals(instanceOptions, _instanceOptions))
		{
			return this;
		}

		ProblemDetailsOptions evaluationOptions = new()
		{
			Title = Title,
			Status = Status,
			Detail = Detail,
			Instance = Instance,
			_titleOptions = titleOptions,
			_detailOptions = detailOptions,
			_instanceOptions = instanceOptions,
		};
		evaluationOptions._parts.AddRange(_parts);
		return evaluationOptions;
	}

	/// <summary>
	///     Describes how the <paramref name="title" /> differs from the expected <see cref="Title" />, or returns
	///     <see langword="null" /> when it matches.
	/// </summary>
	/// <remarks>
	///     Any <paramref name="title" /> matches when no <see cref="Title" /> is expected.
	/// </remarks>
	public ValueTask<string?> GetTitleFailure(string it, ExpectationGrammars grammars, string? title)
		=> GetFailure(_titleOptions, it, "title", grammars, title, Title);

	/// <summary>
	///     Describes how the <paramref name="detail" /> differs from the expected <see cref="Detail" />, or returns
	///     <see langword="null" /> when it matches.
	/// </summary>
	/// <remarks>
	///     Any <paramref name="detail" /> matches when no <see cref="Detail" /> is expected.
	/// </remarks>
	public ValueTask<string?> GetDetailFailure(string it, ExpectationGrammars grammars, string? detail)
		=> GetFailure(_detailOptions, it, "detail", grammars, detail, Detail);

	/// <summary>
	///     Describes how the <paramref name="instance" /> differs from the expected <see cref="Instance" />, or returns
	///     <see langword="null" /> when it matches.
	/// </summary>
	/// <remarks>
	///     Any <paramref name="instance" /> matches when no <see cref="Instance" /> is expected.
	/// </remarks>
	public ValueTask<string?> GetInstanceFailure(string it, ExpectationGrammars grammars, string? instance)
		=> GetFailure(_instanceOptions, it, "instance", grammars, instance, Instance);

	/// <summary>
	///     Indicates whether an absent <paramref name="title" />, <paramref name="detail" /> or <paramref name="instance" />
	///     is expected with a match type that inspects its value.
	/// </summary>
	/// <remarks>
	///     An absent value has no content to inspect, so it fails the expectation and its negation alike.
	/// </remarks>
	public bool InspectsAbsentMember(string? title, string? detail, string? instance)
		=> InspectsAbsentValue(_titleOptions, title) || InspectsAbsentValue(_detailOptions, detail) ||
		   InspectsAbsentValue(_instanceOptions, instance);

	private static bool InspectsAbsentValue(StringEqualityOptions? options, string? actual)
		=> actual is null && options?.InspectsSubject == true;

	private static async ValueTask<string?> GetFailure(StringEqualityOptions? options, string it, string member,
		ExpectationGrammars grammars, string? actual, string? expected)
	{
		if (options is null)
		{
			return null;
		}

		MatchResult result = await options.MatchWithExplanation(actual, expected);
		return result.IsMatch
			? null
			: options.GetExtendedMemberFailure(it, member, grammars, actual, expected, result);
	}

	internal void AppendContexts(ResultContextCollector contexts)
	{
		_titleOptions?.AppendContexts(contexts);
		_detailOptions?.AppendContexts(contexts);
		_instanceOptions?.AppendContexts(contexts);
	}

	/// <inheritdoc cref="object.ToString()" />
#if NET8_0_OR_GREATER
	public override string ToString()
		=> _parts.Count switch
		{
			0 => "",
			1 => $" and {_parts[0].Invoke()}",
			_ => $", {string
				.Join(", ", _parts
					.Take(_parts.Count - 1)
					.Select(part => part.Invoke()))} and {_parts[^1].Invoke()}"
		};
#else
	public override string ToString()
		=> _parts.Count switch
		{
			0 => "",
			1 => $" and {_parts[0].Invoke()}",
			_ => $", {string
				.Join(", ", _parts
					.Take(_parts.Count - 1)
					.Select(part => part.Invoke()))} and {_parts[_parts.Count - 1].Invoke()}"
		};
#endif
}
